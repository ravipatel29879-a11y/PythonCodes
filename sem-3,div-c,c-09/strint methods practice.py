sentence = " java programming is powerful and simple to understand "
print(f"Original Text: '{sentence}'")

print(f"(a) upper(): {sentence.upper()}")
print(f"(b) lower(): {sentence.lower()}")
print(f"(c) title(): {sentence.title()}")
print(f"(d) strip(): '{sentence.strip()}'")
print(f"(e) split(): {sentence.strip().split()}")
print(f"(f) replace spaces: {sentence.strip().replace(' ', '-')}")
print(f"(g) find('a'): {sentence.find('a')}")
