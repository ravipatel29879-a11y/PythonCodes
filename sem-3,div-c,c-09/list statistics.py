values = [18, 76, 25, 54, 82, 91, 43]

print(f"(a) Original List : {values}")
print(f"(b) Sorted List   : {sorted(values)}")
print(f"(c) Reversed List : {list(reversed(values))}")
print(f"(d) Maximum       : {max(values)}")
print(f"(e) Minimum       : {min(values)}")
print(f"(f) Sum           : {sum(values)}")
print(f"(g) Average       : {sum(values) / len(values):.2f}")
